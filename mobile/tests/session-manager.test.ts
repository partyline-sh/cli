import { createElement } from 'react';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { afterEach, expect, it, vi } from 'vitest';
import type { Computer, Delivery, PartylineController, Session } from '../src/runtime/types';
import { SavedSessionBrowser } from '../src/ui/SavedSessionBrowser';
import { CloseSessionButton } from '../src/ui/CloseSessionButton';
const mocks = vi.hoisted(() => ({ controller: {} as PartylineController, alert: vi.fn(), push: vi.fn() }));
vi.mock('../src/runtime', () => ({ usePartyline: () => mocks.controller }));
vi.mock('expo-router', () => ({ router: { push: mocks.push } }));
vi.mock('react-native', () => ({ Alert: { alert: mocks.alert }, Platform: { OS: 'ios', select: () => 'monospace' }, Modal: 'Modal', KeyboardAvoidingView: 'KeyboardAvoidingView', Pressable: 'Pressable', ScrollView: 'ScrollView', Text: 'Text', TextInput: 'TextInput', View: 'View', StyleSheet: { create: (s: unknown) => s } }));
vi.mock('react-native-safe-area-context', () => ({ SafeAreaView: 'SafeAreaView' }));
vi.mock('../src/ui/ControlDelivery', () => ({ ControlDelivery: () => null }));
Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true });
let tree: ReactTestRenderer;
afterEach(async () => { await act(async () => tree?.unmount()); vi.useRealTimers(); vi.clearAllMocks(); });
const computer: Computer = { id: 'pc', name: 'Monolith', connection: 'connected', capabilities: ['session_manager'], relay: '', pairedAt: 0 };
const session: Session = { id: 'pc:%2', computerId: 'pc', key: 'native-session', pane: '%2', title: 'Fix billing', engine: 'claude', state: 'working' };
it('requires confirmation before stopping a working agent and binds the native session identity', async () => {
 const close = vi.fn().mockResolvedValue({ id: 'close1' });
 mocks.controller = { computers: [computer], deliveries: [], closeSavedSession: close } as unknown as PartylineController;
 await act(async () => { tree = create(createElement(CloseSessionButton, { session })); });
 const stop = vi.fn();
 await act(async () => tree.root.findByType('Pressable' as never).props.onPress({ stopPropagation: stop }));
 expect(stop).toHaveBeenCalledOnce(); expect(close).not.toHaveBeenCalled();
 const [, body, buttons] = mocks.alert.mock.calls[0];
 expect(body).toContain('work in progress'); expect(body).toContain('saved conversation stays');
 expect(buttons[0].style).toBe('cancel');
 await act(async () => buttons[1].onPress());
 expect(close).toHaveBeenCalledExactlyOnceWith('pc', '%2', 'native-session');
});
it('loads saved history and waits for the host-confirmed pane before navigating', async () => {
 vi.useFakeTimers();
 const list = vi.fn().mockResolvedValue({ sessions: [{ key: 'saved', engine: 'codex', title: 'Old task', project: '/repo', updatedAt: '' }], total: 1 });
 const open = vi.fn().mockResolvedValue({ id: 'opening', status: 'waiting' });
 mocks.controller = { computers: [computer], sessions: [], deliveries: [], listSavedSessions: list, openSavedSession: open } as unknown as PartylineController;
 await act(async () => { tree = create(createElement(SavedSessionBrowser, { computer })); });
 await act(async () => tree.root.findByProps({ accessibilityLabel: 'All sessions on Monolith' }).props.onPress());
 await act(async () => { await vi.advanceTimersByTimeAsync(300); });
 expect(list).toHaveBeenCalledWith('pc', '', 0);
 await act(async () => tree.root.findByProps({ accessibilityLabel: 'Open Old task' }).props.onPress());
 expect(open).toHaveBeenCalledExactlyOnceWith('pc', 'codex', 'saved'); expect(mocks.push).not.toHaveBeenCalled();
 mocks.controller = { ...mocks.controller, deliveries: [{ id: 'opening', computerId: 'pc', pane: 'saved:codex:saved', status: 'confirmed', data: { pane: '%123' } } as Delivery] };
 await act(async () => tree.update(createElement(SavedSessionBrowser, { computer })));
 await act(async () => { await vi.advanceTimersByTimeAsync(1); });
 expect(mocks.push).toHaveBeenCalledOnce(); expect(mocks.push.mock.calls[0][0].params.computer).toBe('pc');
});
it('ignores an older search response arriving after a newer query', async () => {
 vi.useFakeTimers();
 let oldResult!: (data: unknown) => void;
 const list = vi.fn().mockImplementationOnce(() => new Promise(resolve => { oldResult = resolve; })).mockResolvedValue({ sessions: [{ key: 'new', engine: 'codex', title: 'New result', project: '/repo', updatedAt: '' }], total: 1 });
 mocks.controller = { computers: [computer], sessions: [], deliveries: [], listSavedSessions: list, openSavedSession: vi.fn() } as unknown as PartylineController;
 await act(async () => { tree = create(createElement(SavedSessionBrowser, { computer })); });
 await act(async () => tree.root.findByProps({ accessibilityLabel: 'All sessions on Monolith' }).props.onPress());
 await act(async () => { await vi.advanceTimersByTimeAsync(300); });
 await act(async () => tree.root.findByProps({ accessibilityLabel: 'Search saved sessions' }).props.onChangeText('new'));
 await act(async () => { await vi.advanceTimersByTimeAsync(300); });
 await act(async () => oldResult({ sessions: [{ key: 'old', title: 'Stale result', engine: 'claude' }], total: 1 }));
 expect(JSON.stringify(tree.toJSON())).toContain('New result');
 expect(JSON.stringify(tree.toJSON())).not.toContain('Stale result');
});
it('confirms closing a shared shell and sends its displayed process identity', async () => {
 const close = vi.fn().mockResolvedValue({ id: 'terminal-close' });
 const host = { ...computer, capabilities: ['terminal_controls'] };
 mocks.controller = { computers: [host], deliveries: [], closeSharedTerminal: close } as unknown as PartylineController;
 const shell = { ...session, key: undefined, engine: '', terminalTarget: 'pane:123:/dev/pts/4' };
 await act(async () => { tree = create(createElement(CloseSessionButton, { session: shell })); });
 await act(async () => tree.root.findByType('Pressable' as never).props.onPress({ stopPropagation: vi.fn() }));
 expect(close).not.toHaveBeenCalled();
 const [title, body, buttons] = mocks.alert.mock.calls[0];
 expect(title).toBe('Close terminal?'); expect(body).toContain('work in progress');
 await act(async () => buttons[1].onPress());
 expect(close).toHaveBeenCalledExactlyOnceWith('pc', '%2', 'pane:123:/dev/pts/4');
});

it('does not offer closing against saved, unverified session metadata', async () => {
  mocks.controller = { computers: [computer], deliveries: [], closeSavedSession: vi.fn() } as unknown as PartylineController;
  await act(async () => { tree = create(createElement(CloseSessionButton, { session: { ...session, cached: true } })); });
  expect(tree.toJSON()).toBeNull();
  await act(async () => tree.update(createElement(CloseSessionButton, { session: { ...session, cached: false } })));
  expect(tree.root.findAllByType('Pressable' as never)).toHaveLength(1);
});
