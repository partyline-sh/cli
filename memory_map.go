package main

// THE DERIVED MAP: the facts, rendered into the file every engine already reads.
//
// The design error in the old context threads was that `recall` was a TOOL. 146 facts sat behind
// an optional call with a primer politely asking agents to make it, and the call was simply not
// made. Hooks fix that per turn, but three of the four engines gate hooks behind a trust grant and
// codex fails SILENTLY when it is missing — a hook that injects nothing looks exactly like a hook
// that works.
//
// So the file is the floor and the hook is the enhancement. `CLAUDE.md`, `AGENTS.md` and
// `GEMINI.md` are read at session start by every engine, with no model discretion and no trust
// prompt. Writing the map there means a checkout carries its own context to whatever the next
// person runs, including engines partyline has never heard of.
//
// TWO RULES THIS FILE EXISTS TO ENFORCE:
//
//  1. Never clobber what a human wrote. The map lives between managed markers and is replaced in
//     place; prose around it is untouched. This is why it is an upsert and not a write.
//  2. The map has a FIXED SHAPE. The old thread had no shape, so anything fit — host disk space
//     and receipt numbers filed beside interface contracts. Named sections mean a fact either has
//     a home or does not belong, which is what makes the scope gate mechanical rather than a
//     matter of taste. Empty sections are left in: a gap is information.

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

const mapBegin = "<!-- partyline:memory BEGIN (generated by ptln memory from memory/*.md; edits here are overwritten) -->"
const mapEnd = "<!-- partyline:memory END -->"

// memoryMapCap bounds the rendered map.
//
// The value matches `workerContextCap` (work.go:160), which solved this same problem for injected
// worker context. It is restated here rather than imported because work.go is deleted in phase 5
// and the memory layer has to outlive it. An unbounded map is not a theoretical worry: a seeded
// legacy repo can emit hundreds of facts, and every one of them would land in every teammate's
// prompt on their next pull.
const memoryMapCap = 8 << 10

// mapSection is one named section of the map, in render order.
//
// `what this is` and `architecture and seams` are not kinds — they are sourced by tag, because a
// repo's purpose and its seams are usually recorded as constraints or decisions and would
// otherwise scatter. A fact lands in exactly ONE section: tag first, then kind.
type mapSection struct {
	title string
	kind  string // matched against fact.Kind when tag is empty
	tag   string // matched against fact.Tags, and takes precedence over any kind
	empty string // shown when the section has nothing, so a gap reads as a gap
}

// Only the overview is shown when empty: it is the one section a reader needs before anything
// else, and its absence is worth stating. An empty heading for any other section is noise.
var mapSections = []mapSection{
	{title: "Overview", kind: "overview", empty: "No overview has been written. `ptln memory build --apply` generates one; `ptln memory add overview \"...\"` records one by hand."},
	{title: "Architecture", tag: "architecture"},
	{title: "Interface contracts", kind: "contract"},
	{title: "Constraints", kind: "constraint"},
	{title: "Decisions", kind: "decision"},
	{title: "Gotchas", kind: "gotcha"},
	{title: "Open questions", kind: "question"},
}

// mapDropOrder is the order facts are DROPPED in when the map exceeds memoryMapCap, least valuable
// first. A question is the first to go because it states that something is unknown, which is the
// cheapest thing to lose; a contract is last because another component depends on it being true.
// The overview is never dropped: it is what makes the rest readable.
var mapDropOrder = []string{"question", "gotcha", "decision", "constraint", "contract"}

// sectionFor returns the index of the section a fact belongs to, or -1 if it has no home. The
// overview and open questions are placed by kind alone, so a tag cannot move a question into the
// prose overview or the overview into a bullet list.
func sectionFor(f fact) int {
	if f.Kind == "overview" || f.Kind == "question" {
		for i, s := range mapSections {
			if s.kind == f.Kind {
				return i
			}
		}
	}
	for i, s := range mapSections {
		if s.tag == "" {
			continue
		}
		for _, t := range f.Tags {
			if strings.EqualFold(strings.TrimSpace(t), s.tag) {
				return i
			}
		}
	}
	for i, s := range mapSections {
		if s.kind != "" && s.kind == f.Kind {
			return i
		}
	}
	return -1
}

// renderMemoryMap builds the managed block. Returns "" when there is nothing to say, so a repo
// with no facts gets no block rather than a page of empty headings.
func renderMemoryMap(repoName string, facts []fact) string {
	kept := capFacts(facts, memoryMapCap)
	if len(kept) == 0 {
		return ""
	}

	buckets := make([][]fact, len(mapSections))
	for _, f := range kept {
		if i := sectionFor(f); i >= 0 {
			buckets[i] = append(buckets[i], f)
		}
	}
	// Newest first within a section: a fact rewritten today is likelier to be the current truth
	// than one written months ago and never revisited.
	for i := range buckets {
		sort.SliceStable(buckets[i], func(a, b int) bool {
			return factWhen(buckets[i][a]).After(factWhen(buckets[i][b]))
		})
	}

	var sb strings.Builder
	sb.WriteString(mapBegin + "\n")
	fmt.Fprintf(&sb, "\n## Repository memory: %s\n\n", repoName)
	sb.WriteString("Facts about this repository, one file each in `memory/`. Treat them as correct unless the code\n")
	sb.WriteString("contradicts them, and report any contradiction. Record a new decision, constraint, contract or\n")
	sb.WriteString("gotcha with `ptln memory add <kind> \"...\"`, and correct a wrong entry with\n")
	sb.WriteString("`ptln memory edit <id> \"...\"`. A decision says what was chosen, why, and what it costs. Name the\n")
	sb.WriteString("evidence for each fact; if you cannot verify something, add a `question` instead of a guess.\n")
	sb.WriteString("Do not commit `memory/` or this file; the user commits them.\n")
	sb.WriteString(loopGuidePointer + "\n")

	for i, s := range mapSections {
		if len(buckets[i]) == 0 {
			if s.empty != "" {
				fmt.Fprintf(&sb, "\n### %s\n\n%s\n", s.title, s.empty)
			}
			continue
		}
		fmt.Fprintf(&sb, "\n### %s\n\n", s.title)
		// The FULL id, not a short prefix: ids start with the date, so truncating makes every
		// fact recorded on one day render identically, and the map would be citing an id that
		// `ptln memory edit` cannot resolve to a single fact.
		for _, f := range buckets[i] {
			if s.kind == "overview" {
				fmt.Fprintf(&sb, "%s\n\n`%s`\n", strings.TrimSpace(f.Body), f.ID)
				continue
			}
			fmt.Fprintf(&sb, "- %s (`%s`)\n", mapLine(f.Body), f.ID)
		}
	}
	if n := len(facts) - len(kept); n > 0 {
		fmt.Fprintf(&sb, "\n_%d more fact(s) not shown — the map is capped so it cannot crowd out the task. `ptln memory ls` has all of them._\n", n)
	}
	sb.WriteString("\n" + mapEnd)
	return sb.String()
}

// factWhen is a fact's effective time: when it was last rewritten, else when it was recorded.
func factWhen(f fact) time.Time {
	if !f.Updated.IsZero() {
		return f.Updated
	}
	return f.At
}

// mapLine flattens a multi-paragraph body onto one bullet. It does not truncate: an entry cut off
// mid-sentence is worse than a long one, and memoryMapCap bounds the total.
func mapLine(body string) string {
	return strings.Join(strings.Fields(strings.TrimSpace(body)), " ")
}

// capFacts drops facts until the rendered map fits, least valuable kind first (mapDropOrder), and
// oldest first within a kind. It never drops below one fact per populated section while anything
// lower-priority remains, so a cap cannot silently delete an entire category.
func capFacts(facts []fact, cap int) []fact {
	kept := append([]fact(nil), facts...)
	for _, kind := range mapDropOrder {
		if renderedSize(kept) <= cap {
			break
		}
		// Oldest of this kind goes first.
		for {
			idx := -1
			for i, f := range kept {
				if f.Kind != kind {
					continue
				}
				if idx == -1 || factWhen(f).Before(factWhen(kept[idx])) {
					idx = i
				}
			}
			if idx == -1 || renderedSize(kept) <= cap {
				break
			}
			kept = append(kept[:idx], kept[idx+1:]...)
		}
	}
	return kept
}

// renderedSize measures only the fact lines, which is what actually grows. The headings are a
// fixed cost and counting them would make the cap depend on the section list.
func renderedSize(facts []fact) int {
	n := 0
	for _, f := range facts {
		n += len(f.Body) + len(f.ID) + 8
	}
	return n
}

// memoryMapFiles are the per-engine memory filenames, AGENTS.md first: it is the neutral standard
// and the reason this reaches engines partyline has no integration with.
var memoryMapFiles = []string{"AGENTS.md", "CLAUDE.md", "GEMINI.md"}

// writeMemoryMap renders the repo's facts into whichever engine memory files the repo already has.
//
// It only CREATES a file when the repo has none of them, and then only AGENTS.md. Creating three
// files in someone's repository because they recorded one fact is not a reasonable thing for a
// tool to do unasked; updating the ones they already keep is.
func writeMemoryMap(repoRoot string) ([]string, error) {
	if repoRoot == "" {
		return nil, nil
	}
	facts, err := readFacts(repoRoot, false)
	if err != nil {
		return nil, err
	}
	block := renderMemoryMap(filepath.Base(repoRoot), facts)

	existing := make([]string, 0, len(memoryMapFiles))
	for _, name := range memoryMapFiles {
		if fileExists(filepath.Join(repoRoot, name)) {
			existing = append(existing, name)
		}
	}
	if len(existing) == 0 {
		if block == "" {
			return nil, nil // nothing to say and nothing to say it in
		}
		existing = []string{memoryMapFiles[0]}
	}

	for _, name := range existing {
		p := filepath.Join(repoRoot, name)
		if block == "" {
			stripManagedBlock(p, mapBegin, mapEnd)
			continue
		}
		injectManagedBlock(p, mapBegin, mapEnd, block)
	}
	return existing, nil
}

// stripManagedBlock removes the managed block from a file, and removes the file entirely if the
// block was all it contained — the mirror of writeMemoryMap creating it. Without this, deleting
// your last fact would leave a stray AGENTS.md that partyline created and never cleans up.
func stripManagedBlock(path, begin, end string) {
	b, err := os.ReadFile(path)
	if err != nil {
		return
	}
	content := string(b)
	i := strings.Index(content, begin)
	if i < 0 {
		return
	}
	j := strings.Index(content[i:], end)
	if j < 0 {
		return
	}
	rest := strings.TrimSpace(content[:i] + content[i+j+len(end):])
	if rest == "" {
		_ = os.Remove(path)
		return
	}
	_ = os.WriteFile(path, []byte(rest+"\n"), 0o644)
}

// refreshMemoryMap regenerates the engine memory files after a fact changes.
//
// Called from the command layer rather than from writeFact, for two reasons: the store's job is to
// write a fact, not to maintain a derived artifact; and a bulk seed that re-rendered the whole map
// once per fact would be quadratic. `ptln memory build` calls this ONCE when it finishes.
//
// Best-effort and non-fatal: the facts are the source of truth and are already safely on disk, so
// a failure to regenerate a convenience file must never fail the write that prompted it.
func refreshMemoryMap(ws *projectWorkspace) {
	if ws == nil || !ws.repoLocal {
		return
	}
	files, err := writeMemoryMap(ws.Dir)
	if err != nil {
		fmt.Printf("  (the fact is saved, but the engine memory files could not be updated: %v)\n", err)
		return
	}
	if len(files) > 0 {
		fmt.Printf("  %s updated — the next session on any engine reads this\n", strings.Join(files, ", "))
	}
}

// memoryMapCmd is `ptln memory map` — regenerate the engine memory files by hand.
//
// Normally unnecessary, because every fact mutation refreshes them. It exists for the cases where
// they drift anyway: a merge that took someone else's block, a file restored from a stale branch,
// or a fact edited by hand in the repo rather than through the CLI.
func memoryMapCmd() {
	ws, _ := workspaceHere()
	if !ws.repoLocal {
		fatal(fmt.Errorf("the map is written into the repo being worked on, and this is a legacy side-repo project\n  run this inside the code repo instead"))
	}
	files, err := writeMemoryMap(ws.Dir)
	if err != nil {
		fatal(err)
	}
	if len(files) == 0 {
		fmt.Println("nothing recorded yet — no map to write")
		return
	}
	fmt.Printf("✓ %s\n", strings.Join(files, ", "))
}
